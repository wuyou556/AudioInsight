async def mock_transcribe(file_path: str) -> str:
    """
    Mock transcription service that simulates ASR processing.

    Args:
        file_path: Path to the audio file (not actually used in mock)

    Returns:
        Transcribed text

    Raises:
        Exception: 20% probability to simulate transcription failure
    """
    # Random delay between 5-15 seconds
    delay = random.uniform(5.0, 15.0)
    logger.info(f"Mock transcription started for {file_path}, will take {delay:.1f} seconds")
    await asyncio.sleep(delay)

    # 20% probability of failure
    if random.random() < 0.2:
        error_messages = [
            "音频格式解码失败",
            "音频质量过低，无法识别",
            "音频时长超出限制",
            "ASR 服务暂时不可用",
            "音频文件损坏"
        ]
        error = random.choice(error_messages)
        logger.warning(f"Mock transcription failed for {file_path}: {error}")
        raise Exception(error)

    # Success: return random transcript
    transcript = random.choice(TRANSCRIPTION_SAMPLES)
    logger.info(f"Mock transcription completed for {file_path}, {len(transcript)} characters")
    return transcript
